const normalizeKey = (value) =>
  String(value || "")
    .replace(/\s+/g, " ")
    .trim();

const normalizeRegionName = (value) =>
  normalizeKey(value)
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase();

const buildRegionTranslations = () => {
  const regions = new Map();

  try {
    const englishNames = new Intl.DisplayNames(["en"], { type: "region" });
    const arabicNames = new Intl.DisplayNames(["ar"], { type: "region" });

    for (let first = 65; first <= 90; first += 1) {
      for (let second = 65; second <= 90; second += 1) {
        const code = `${String.fromCharCode(first)}${String.fromCharCode(
          second
        )}`;

        try {
          const englishName = englishNames.of(code);
          const arabicName = arabicNames.of(code);

          if (englishName && arabicName && englishName !== code) {
            regions.set(normalizeRegionName(englishName), arabicName);
          }
        } catch {
          // Ignore invalid region codes.
        }
      }
    }
  } catch {
    return regions;
  }

  return regions;
};

const regionTranslations = buildRegionTranslations();

export const t = (value) => {
  const key = normalizeKey(value);
  if (translations[key]) return translations[key];

  const lastDaysMatch = key.match(/^Last (\d+) Days$/i);
  if (lastDaysMatch) return `آخر ${lastDaysMatch[1]} يوم`;

  const appointmentsLastDaysMatch = key.match(
    /^Appointments in the Last (\d+) Days$/i
  );
  if (appointmentsLastDaysMatch) {
    return `المواعيد خلال آخر ${appointmentsLastDaysMatch[1]} يوم`;
  }

  const transactionsLastDaysMatch = key.match(
    /^Transactions in the Last (\d+) Days$/i
  );
  if (transactionsLastDaysMatch) {
    return `المعاملات خلال آخر ${transactionsLastDaysMatch[1]} يوم`;
  }

  const usersLastDaysMatch = key.match(
    /^Users Registration in the Last (\d+) Days$/i
  );
  if (usersLastDaysMatch) {
    return `تسجيل المستخدمين خلال آخر ${usersLastDaysMatch[1]} يوم`;
  }

  const patientsLastDaysMatch = key.match(
    /^Patients Registration in the Last (\d+) Days$/i
  );
  if (patientsLastDaysMatch) {
    return `تسجيل المرضى خلال آخر ${patientsLastDaysMatch[1]} يوم`;
  }

  const appointmentsMadeLastDaysMatch = key.match(
    /^Appointments Made in the Last (\d+) Days$/i
  );
  if (appointmentsMadeLastDaysMatch) {
    return `المواعيد المنشأة خلال آخر ${appointmentsMadeLastDaysMatch[1]} يوم`;
  }

  const caseMatch = Object.keys(translations).find(
    (translationKey) => translationKey.toLowerCase() === key.toLowerCase()
  );
  if (caseMatch) return translations[caseMatch];

  const readable = key.replace(/_/g, " ").replace(/-/g, " ");
  const readableCaseMatch = Object.keys(translations).find(
    (translationKey) =>
      translationKey.toLowerCase() === readable.toLowerCase()
  );

  return translations[readable] || translations[readableCaseMatch] || readable;
};

const translateKnown = (value) => {
  const key = normalizeKey(value);
  if (!key) return null;

  const regionTranslation = regionTranslations.get(normalizeRegionName(key));
  if (regionTranslation) return regionTranslation;

  const translated = t(key);
  if (translated !== key && translated !== key.replace(/_/g, " ").replace(/-/g, " ")) {
    return translated;
  }

  const colonMatch = key.match(/^(.+):$/);
  if (colonMatch) {
    const colonTranslation = translateKnown(colonMatch[1]);
    if (colonTranslation) return `${colonTranslation}:`;
  }

  return translations[key] || null;
};

const translateNode = (node) => {
  if (!node || node.nodeType !== Node.TEXT_NODE) return;
  const current = node.nodeValue;
  const leading = current.match(/^\s*/)?.[0] || "";
  const trailing = current.match(/\s*$/)?.[0] || "";
  const translated = translateKnown(current);

  if (translated) {
    node.nodeValue = `${leading}${translated}${trailing}`;
  }
};

const translateElementAttributes = (element) => {
  ["placeholder", "aria-label", "title"].forEach((attr) => {
    const value = element.getAttribute(attr);
    const translated = translateKnown(value);
    if (translated) element.setAttribute(attr, translated);
  });
};

const translateTree = (root) => {
  if (!root) return;

  if (root.nodeType === Node.TEXT_NODE) {
    translateNode(root);
    return;
  }

  if (root.nodeType !== Node.ELEMENT_NODE) return;

  translateElementAttributes(root);

  const walker = document.createTreeWalker(
    root,
    NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT,
    {
      acceptNode(node) {
        const parent = node.parentElement;
        if (parent?.closest("script, style, code, pre, [data-no-translate]")) {
          return NodeFilter.FILTER_REJECT;
        }
        return NodeFilter.FILTER_ACCEPT;
      },
    }
  );

  let node = walker.currentNode;
  while (node) {
    if (node.nodeType === Node.TEXT_NODE) translateNode(node);
    if (node.nodeType === Node.ELEMENT_NODE) translateElementAttributes(node);
    node = walker.nextNode();
  }
};

export const initArabicUi = () => {
  document.documentElement.lang = "ar";
  document.documentElement.dir = "rtl";
  document.body.dir = "rtl";

  translateTree(document.body);

  const observer = new MutationObserver((mutations) => {
    window.requestAnimationFrame(() => {
      mutations.forEach((mutation) => {
        if (mutation.type === "characterData") {
          translateNode(mutation.target);
        }

        mutation.addedNodes.forEach((node) => translateTree(node));

        if (mutation.type === "attributes") {
          translateElementAttributes(mutation.target);
        }
      });
    });
  });

  observer.observe(document.body, {
    childList: true,
    subtree: true,
    characterData: true,
    attributes: true,
    attributeFilter: ["placeholder", "aria-label", "title"],
  });

  return observer;
};
